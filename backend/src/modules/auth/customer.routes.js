const router = require('express').Router();
const rateLimit = require('express-rate-limit');
const { requireAuth, requireRole } = require('../../middleware/auth');
const c = require('./customer.controller');
const limit = rateLimit({ windowMs: 15 * 60 * 1000, limit: 10, message: { message: 'Too many account attempts. Please try again later.' } });
const forgotPasswordIpLimit = rateLimit({ windowMs: 15 * 60 * 1000, limit: 5, message: { message: 'Too many account attempts. Please try again later.' } });
router.post('/register', limit, c.register);
router.post('/login', limit, c.login);
router.post('/logout', c.logout);
router.post('/forgot-password', forgotPasswordIpLimit, c.forgotPassword);
router.post('/reset-password', limit, c.resetPassword);
router.post('/change-password', requireAuth('customer'), requireRole('customer'), c.changePassword);
router.get('/me', requireAuth('customer'), requireRole('customer'), c.me);
router.patch('/me', requireAuth('customer'), requireRole('customer'), c.update);
module.exports = router;
